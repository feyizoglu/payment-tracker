// Turns the source word lists into Secret Word's five-letter word lists.
// Run by scripts/secret-word/build-dictionary.ts; the game reads only the generated tr.ts and en.ts.

import { SECRET_ALPHABET, SECRET_LEN, secretUpper } from "../secret-word-letters";

const fiveOf = (alphabet: readonly string[], word: string) => {
  const letters = [...word];
  return letters.length === SECRET_LEN && letters.every((l) => alphabet.includes(l));
};

// Zemberek tags: punctuation, numbers, pronouns, interjections, reduplications and function words are
// not words a player would guess.
const TR_SKIP = /\bP:(Punc|Num|Pron|Interj|Dup|Postp|Conj|Ques|Det)\b/;

/**
 * Five-letter headwords from Zemberek's master-dictionary.dict, circumflexes flattened (â is a). Verbs
 * are listed as infinitives (beklemek), so a verb also gives its stem (BEKLE); a line with a part of
 * speech (ekmek [P:Noun]) is never a verb.
 */
export function turkishRoots(dict: string): string[] {
  const out = new Set<string>();
  for (const line of dict.split("\n")) {
    if (!line.trim() || line.startsWith("#") || TR_SKIP.test(line)) continue;
    const raw = line.split(" [")[0].trim();
    if (raw !== raw.toLocaleLowerCase("tr")) continue;
    const word = secretUpper(raw.replace(/â/g, "a").replace(/î/g, "i").replace(/û/g, "u"), "tr");
    const forms = !/\bP:/.test(line) && /M[AE]K$/.test(word) ? [word, word.slice(0, -3)] : [word];
    for (const form of forms) if (fiveOf(SECRET_ALPHABET.tr, form)) out.add(form);
  }
  return [...out].sort();
}

// Words that end like an inflection of another ENABLE word but are words of their own.
const EN_KEEP = new Set([
  "CHAOS", "KUDOS", "JEANS", "PANTS", "TONGS", "YOURS", "DREGS", "GOODS", "MEANS",
  "BREED", "GREED", "TWEED", "JADED", "BEING", "THING", "ICING",
]);

/**
 * Five-letter words from the ENABLE list without the inflections of another word: plurals and verb
 * forms in -s, -es, -ies (cry) and -ves (elf, wife), and -ed and -ing forms. Irregular forms
 * (teeth, geese) stay.
 */
export function englishRoots(enable: string): string[] {
  const all = new Set(enable.split("\n").map((w) => w.trim().toUpperCase()).filter(Boolean));
  const has = (w: string) => all.has(w);
  const inflected = (w: string) => {
    if (EN_KEEP.has(w)) return false;
    if (w.endsWith("IES") && has(w.slice(0, -3) + "Y")) return true;
    if (w.endsWith("VES") && (has(w.slice(0, -3) + "F") || has(w.slice(0, -3) + "FE"))) return true;
    if (w.endsWith("S") && !/(SS|US|IS)$/.test(w) && (has(w.slice(0, -1)) || (w.endsWith("ES") && has(w.slice(0, -2))))) return true;
    if (w.endsWith("ED")) {
      const stem = w.slice(0, -2);
      if (has(stem) || has(w.slice(0, -1)) || (stem.at(-1) === stem.at(-2) && has(stem.slice(0, -1)))) return true;
    }
    if (w.endsWith("ING") && (has(w.slice(0, -3)) || has(w.slice(0, -3) + "E"))) return true;
    return false;
  };
  return [...all].filter((w) => fiveOf(SECRET_ALPHABET.en, w) && !inflected(w)).sort();
}

/** The generated module for one language. */
export function wordsModule(name: string, source: string, words: readonly string[]): string {
  return `// Generated by scripts/secret-word/build-dictionary.ts from ${source}. Do not edit; see NOTICE.md.
export const ${name} = "${words.join(" ")}";
`;
}
