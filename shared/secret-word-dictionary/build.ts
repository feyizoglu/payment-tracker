// Turns the source word lists into Secret Word's five-letter root lists.
// Run by scripts/secret-word/build-dictionary.ts; the game reads only the generated tr.ts and en.ts.

import { SECRET_ALPHABET, SECRET_LEN, secretUpper } from "../secret-word";

const fiveOf = (alphabet: readonly string[], word: string) => {
  const letters = [...word];
  return letters.length === SECRET_LEN && letters.every((l) => alphabet.includes(l));
};

// Zemberek tags: punctuation, numbers, pronouns, interjections, reduplications and function words are
// not words a player would guess.
const TR_SKIP = /\bP:(Punc|Num|Pron|Interj|Dup|Postp|Conj|Ques|Det)\b/;

/** Five-letter roots from Zemberek's master-dictionary.dict, circumflexes flattened (â is a). */
export function turkishRoots(dict: string): string[] {
  const out = new Set<string>();
  for (const line of dict.split("\n")) {
    if (!line.trim() || line.startsWith("#") || TR_SKIP.test(line)) continue;
    const raw = line.split(" [")[0].trim();
    if (raw !== raw.toLocaleLowerCase("tr")) continue;
    const word = secretUpper(raw.replace(/â/g, "a").replace(/î/g, "i").replace(/û/g, "u"), "tr");
    if (fiveOf(SECRET_ALPHABET.tr, word)) out.add(word);
  }
  return [...out].sort();
}

// Words that end like a plural of another ENABLE word but are words of their own.
const EN_KEEP = new Set(["CHAOS", "KUDOS", "JEANS", "PANTS", "TONGS", "YOURS", "DREGS"]);

/** Five-letter words from the ENABLE list, without plurals (an -s or -es on another word). */
export function englishRoots(enable: string): string[] {
  const all = new Set(enable.split("\n").map((w) => w.trim().toUpperCase()).filter(Boolean));
  const plural = (w: string) => {
    if (EN_KEEP.has(w) || !w.endsWith("S") || /(SS|US|IS)$/.test(w)) return false;
    return all.has(w.slice(0, -1)) || (w.endsWith("ES") && all.has(w.slice(0, -2)));
  };
  return [...all].filter((w) => fiveOf(SECRET_ALPHABET.en, w) && !plural(w)).sort();
}

/** The generated module for one language. */
export function wordsModule(name: string, source: string, words: readonly string[]): string {
  return `// Generated by scripts/secret-word/build-dictionary.ts from ${source}. Do not edit; see NOTICE.md.
export const ${name} = "${words.join(" ")}";
`;
}
