import { fileURLToPath } from "node:url";
import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";

const fs = vi.hoisted(() => ({
  readFileSync: vi.fn<(file: string, encoding: string) => string>(),
  writeFileSync: vi.fn<(file: string, data: string) => void>(),
}));

vi.mock("node:fs", () => ({ ...fs, default: fs }));

const SCRIPT = fileURLToPath(new URL("../../scripts/secret-word/build-dictionary.ts", import.meta.url));
const OUT_TR = fileURLToPath(new URL("../../shared/secret-word-dictionary/tr.ts", import.meta.url));
const OUT_EN = fileURLToPath(new URL("../../shared/secret-word-dictionary/en.ts", import.meta.url));
const INPUTS: Record<string, string> = {
  "/in/master-dictionary.dict": ["kitap", "balık [P:Noun]", "ancak [P:Conj]", "horse"].join("\n"),
  "/in/enable1.txt": ["zebra", "horse", "horses", "kitap"].join("\n"),
};

describe("the Secret Word dictionary script", () => {
  const argv = process.argv;

  beforeEach(() => {
    vi.resetModules();
    vi.clearAllMocks();
    fs.readFileSync.mockImplementation((file) => INPUTS[file] ?? "");
    vi.spyOn(console, "log").mockImplementation(() => undefined);
    vi.spyOn(console, "error").mockImplementation(() => undefined);
  });

  afterEach(() => {
    process.argv = argv;
    vi.restoreAllMocks();
  });

  it("writes the Turkish list from the first input to tr.ts and the English list from the second to en.ts", async () => {
    process.argv = [argv[0], SCRIPT, "/in/master-dictionary.dict", "/in/enable1.txt"];
    await import("../../scripts/secret-word/build-dictionary");
    expect(fs.writeFileSync.mock.calls).toEqual([
      [
        OUT_TR,
        `// Generated by scripts/secret-word/build-dictionary.ts from Zemberek's master-dictionary.dict. Do not edit; see NOTICE.md.\nexport const SECRET_WORDS_TR = "BALIK HORSE KİTAP";\n`,
      ],
      [
        OUT_EN,
        '// Generated by scripts/secret-word/build-dictionary.ts from the ENABLE word list. Do not edit; see NOTICE.md.\nexport const SECRET_WORDS_EN = "HORSE KITAP ZEBRA";\n',
      ],
    ]);
  });

  it("prints its usage and exits with 1 when an input is missing, writing nothing", async () => {
    const exit = vi.spyOn(process, "exit").mockImplementation((code) => {
      throw new Error(`exit ${code}`);
    });
    process.argv = [argv[0], SCRIPT, "/in/master-dictionary.dict"];
    await expect(import("../../scripts/secret-word/build-dictionary")).rejects.toThrow("exit 1");
    expect(exit).toHaveBeenCalledWith(1);
    expect(console.error).toHaveBeenCalledWith(expect.stringMatching(/^usage: /));
    expect(fs.writeFileSync).not.toHaveBeenCalled();
  });
});
