import { describe, it, expect } from "vitest";
import { englishRoots, turkishRoots, wordsModule } from "../../shared/secret-word-dictionary/build";
import { SECRET_WORDS_EN } from "../../shared/secret-word-dictionary/en";
import { SECRET_WORDS_TR } from "../../shared/secret-word-dictionary/tr";
import { SECRET_ALPHABET } from "@/lib/secret-word";

describe("turkishRoots", () => {
  it("keeps five-letter roots, upper-cased the Turkish way, with circumflexes flattened", () => {
    const dict = [
      "# comment",
      "kitap",
      "balık",
      "kâğıt",
      "güneş [P:Noun]",
      "çukur [P:Adj]",
      "ermek [A:Aorist_I]",
      "kitaplık",
      "araba",
      "araba",
      "Paris",
      "hayır [P:Interj]",
      "beşer [P:Num]",
      "bunlar [P:Pron]",
      "" ,
    ].join("\n");
    expect(turkishRoots(dict)).toEqual(["ARABA", "BALIK", "ERMEK", "GÜNEŞ", "KAĞIT", "KİTAP", "ÇUKUR"]);
  });
});

describe("englishRoots", () => {
  it("keeps five-letter words, leaving out plurals but not words that only look like one", () => {
    const enable = ["horse", "horses", "tree", "trees", "box", "boxes", "chao", "chaos", "glass", "lotus", "basis", "cat", "zebra", "abcdef", "x-ray", ""].join("\n");
    expect(englishRoots(enable)).toEqual(["BASIS", "CHAOS", "GLASS", "HORSE", "LOTUS", "ZEBRA"]);
  });
});

describe("wordsModule", () => {
  it("writes one exported string with its source", () => {
    expect(wordsModule("SECRET_WORDS_XX", "a test", ["ABCDE", "FGHIJ"])).toBe(
      '// Generated by scripts/secret-word/build-dictionary.ts from a test. Do not edit; see NOTICE.md.\nexport const SECRET_WORDS_XX = "ABCDE FGHIJ";\n'
    );
  });
});

describe("the generated word lists", () => {
  it("hold thousands of sorted, unique five-letter words of each alphabet", () => {
    for (const [lang, list] of [["tr", SECRET_WORDS_TR], ["en", SECRET_WORDS_EN]] as const) {
      const words = list.split(" ");
      expect(words.length).toBeGreaterThan(4000);
      expect(new Set(words).size).toBe(words.length);
      expect([...words].sort()).toEqual(words);
      expect(words.every((w) => [...w].length === 5 && [...w].every((l) => SECRET_ALPHABET[lang].includes(l)))).toBe(true);
    }
  });
});
